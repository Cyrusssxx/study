def find_section(chapters, sec_name):
    for c in chapters:
        for s in c["sections"]:
            if s["section"].strip() == sec_name:
                return s
    return None

def add_ss(section, title, html, order_key):
    for ss in section.get("subsections", []):
        if ss["section"] == title:
            return False
    ss = {"section": title, "html": html}
    section.setdefault("subsections", [])
    # 按 order_key 排序插入
    section["subsections"].append(ss)
    section["subsections"].sort(key=lambda x: order_key(x["section"]))
    return True

def key_cn(s):
    m = __import__("re").match(r"^(\d+)\.(\d+)\.(\d+)", s)
    return (int(m.group(1)), int(m.group(2)), int(m.group(3))) if m else (99, 99, 99)

def key_simple(s):
    m = __import__("re").match(r"^(\d+)\.(\d+)", s)
    return (int(m.group(1)), int(m.group(2))) if m else (99, 99)

