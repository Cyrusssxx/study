    return ('<table><thead><tr>' + ''.join('<th>%s</th>' % h for h in headers) + '</tr></thead><tbody>'
            + ''.join('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>' for r in rows)
            + '</tbody></table>')


