def clean_code_misclass(it):
    """通用清理：正文行被误判为 pre（如 `Sub=1，因此…`）"""
    an = it['an']
    # 把 pre 内以「，」或中文收尾的非代码行移出——只针对已知模式
    an = an.replace(
        '<pre><code class="language-c">Sub=1，因此CF=C田Sub=0。由于负数-负数的结果仍为负数且非零，因此OF=0、</code></pre>',
        '<p>Sub=1，因此CF=C⊕Sub=0。由于负数−负数的结果仍为负数且非零，因此OF=0、</p>')
    it['an'] = an


def strip_stale(it):
    """清理题干里抽残的 hline/纯图残留数字行（未被 Q 覆盖的选择题）。"""
    q = it['q']
    if 'hline' in q:
        # 保险：去 hline 行
        q = re.sub(r'(<br/>)?hline(</p>)?', '', q)
    it['q'] = q


def main():
    d = json.load(open(F, encoding='utf-8'))
    for it in d['items']:
        n = it['i']
        if n in Q:
            it['q'] = Q[n]
        else:
            strip_stale(it)
        if n in AN:
            it['an'] = AN[n]
        elif n == 41:
            pass
        clean_code_misclass(it)
    with open(F, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    # 简报
    print('题数', len(d['items']))
