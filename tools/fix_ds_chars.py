# 交替替换：T? → T₁,T₂,T₁,T₂,...（按出现顺序）
ALTERNATE = {
    '王道书 5.3.3_大题_14': [('T?', 'T₁', 'T₂')],
}


def apply_all(text, reps):
    for old, new in reps:
        if old in text:
            text = text.replace(old, new)
    return text


def apply_alternate(text, pairs):
    for pat, a, b in pairs:
        out, turn = [], 0
        i = 0
        while True:
            j = text.find(pat, i)
            if j < 0:
                out.append(text[i:])
                break
            out.append(text[i:j] + (a if turn % 2 == 0 else b))
            turn += 1
            i = j + len(pat)
        text = ''.join(out)
    return text


changed = 0
for q in d['questions']:
    src = q.get('source', '')
    reps = list(GLOBAL)
    if src in PER_ENTRY:
        reps += PER_ENTRY[src]
    before = (q.get('content', ''), q.get('answer', ''))
    if 'content' in q:
        q['content'] = apply_all(q['content'], reps)
        if src in ALTERNATE:
            q['content'] = apply_alternate(q['content'], ALTERNATE[src])
    if 'answer' in q:
        q['answer'] = apply_all(q['answer'], reps)
        if src in ALTERNATE:
            q['answer'] = apply_alternate(q['answer'], ALTERNATE[src])
    after = (q.get('content', ''), q.get('answer', ''))
    if before != after:
        changed += 1
        print('fixed:', src)

