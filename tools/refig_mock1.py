def main():
    d = json.load(io.open(DST, encoding='utf-8'))
    items = d['items']
    for it in items:
        n = it['i']
        if n in Q:
            it['q'] = Q[n]
    with io.open(DST, 'w', encoding='utf-8', newline='') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    print('重建完成：%d 题题干' % len(Q))
    print('  ', sorted(Q))

if __name__ == '__main__':
    main()
