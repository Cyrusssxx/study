def table(headers, rows):
    h = '<thead><tr>' + ''.join('<th>%s</th>' % x for x in headers) + '</tr></thead>'
    b = '<tbody>' + ''.join('<tr>' + ''.join('<td>%s</td>' % x for x in row) + '</tr>' for row in rows) + '</tbody>'
    return '<table>' + h + b + '</table>'


