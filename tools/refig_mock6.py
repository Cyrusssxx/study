def strip_stale(it):
    it['q'] = it['q'].replace('\x00', '')
    it['an'] = it['an'].replace('\x00', '')


def main():
    d = json.load(open(F, encoding='utf-8'))
    for it in d['items']:
        n = it['i']
        if n in Q:
            it['q'] = Q[n]
        else:
            strip_stale(it)
        if n in AN:
            it['an'] = AN[n]
        else:
            it['an'] = it['an'].replace('\x00', '')
    with open(F, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    print('题数', len(d['items']))
    for n in [12, 13, 27, 42, 43, 44, 45]:
        it = d['items'][n - 1]
        print('题%d q长=%d fig=%d table=%d pre=%d | an长=%d anpre=%d' % (
            n, len(it['q']), it['q'].count('fig-img'), it['q'].count('<table'), it['q'].count('<pre'),
            len(it['an']), it['an'].count('<pre')))


if __name__ == '__main__':
    main()
