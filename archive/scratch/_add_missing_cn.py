def find(ch_title, sec_title):
    ch = next(c for c in notes['chapters'] if c['chapter'] == ch_title)
    return ch, next(s for s in ch['sections'] if s['section'] == sec_title)

def key(ss):
    m = re.match(r'^(\d+)\.(\d+)\.(\d+)', ss['section'])
    return (int(m.group(1)), int(m.group(2)), int(m.group(3))) if m else (99, 99, 99)

def add(sub):
    sec = sub['section']
    chmap = {'1.': '第1章 计算机网络体系结构', '2.': '第2章 物理层', '3.': '第3章 数据链路层',
             '4.': '第4章 网络层', '5.': '第5章 传输层', '6.': '第6章 应用层'}
    ch_title = chmap[sec[:2]]
    ch = next(c for c in notes['chapters'] if c['chapter'] == ch_title)
    sec_no = '.'.join(sec.split('.')[:2]) + ' '   # '1.1 '
    s = next(s for s in ch['sections'] if s['section'].startswith(sec_no))
    s['subsections'].append(sub)
    s['subsections'].sort(key=key)

for sub in ADD.values():
    add(sub)

