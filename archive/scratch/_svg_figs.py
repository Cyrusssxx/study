# ---------- 替换 ----------
hit = 0
for ch in notes['chapters']:
    for s in ch['sections']:
        for ss in s.get('subsections', []):
            if ss['section'] in FIGS:
                # 移除旧的 ascii-fig 块（含说明 p）
                h = ss['html']
                h = re.sub(r'<p class="paragraph"><b>示意图（[^<]*）</b>：</p><pre class="ascii-fig">.*?</pre>\n?', '', h, flags=re.S)
                # 追加 SVG 图
                ss['html'] = h + '<p class="paragraph"><b>示意图：</b></p>' + FIGS[ss['section']]
                hit += 1
missing = [k for k in FIGS if k not in [ss['section'] for c in notes['chapters'] for s in c['sections'] for ss in s.get('subsections',[])]]
print(f'已替换 {hit} 张 SVG', '| 未匹配:', missing if missing else '无')

with open(SRC, 'w', encoding='utf-8') as f:
    json.dump(notes, f, ensure_ascii=False, indent=2)
    f.write('\n')
