def split_by_h4(html):
    parts = re.split(r'(<h4>[^<]+</h4>)', html)
    blocks, cur = [], None
    for p in parts:
        m = re.match(r'<h4>([^<]+)</h4>', p)
        if m:
            cur = m.group(1)
            blocks.append([cur, p])
        elif cur is not None:
            blocks[-1][1] += p
    return blocks

def rebuild(section, sec_map):
    blocks = split_by_h4(section['html'])
    by_title = {t: h for t, h in blocks}
    for _, titles in sec_map:
        for t in titles:
            if t not in by_title:
                raise SystemExit(f'映射缺失: {section["section"]} -> {t!r}')
    used = set()
    subsections = []
    for sub_name, titles in sec_map:
        for t in titles: used.add(t)
        subsections.append({'section': sub_name, 'html': ''.join(by_title[t] for t in titles)})
    tail = ''.join(h for t, h in blocks if t not in used)
    new_sec = {'section': section['section'], 'html': tail, 'subsections': subsections}
    return new_sec

changed = 0
for ch in notes['chapters']:
    chmap = M.get(ch['chapter'])
    if not chmap: continue
    new_secs = []
    for s in ch['sections']:
        if 'subsections' in s:          # 幂等：已拆过（第4章）
            new_secs.append(s); continue
        sec_map = chmap.get(s['section'])
        if not sec_map:                 # 教材无标准小节（1.4/1.5/2.4等）
            new_secs.append(s); continue
        new_secs.append(rebuild(s, sec_map))
        changed += 1
    ch['sections'] = new_secs

with open(SRC, 'w', encoding='utf-8') as f:
    json.dump(notes, f, ensure_ascii=False, indent=2)
    f.write('\n')

print(f'已拆 {changed} 个节')
for ch in notes['chapters']:
    n_sub = sum(len(s.get('subsections', [])) for s in ch['sections'])
    print(f'  {ch["chapter"]}: {n_sub} 个小节')
