def svg(id_, w, h, body):
    return (f'<figure class="struct-fig"><svg class="struct-svg" viewBox="0 0 {w} {h}" xmlns="http://www.w3.org/2000/svg">'
            f'<defs><marker id="arr{id_}" markerWidth="9" markerHeight="9" refX="7" refY="4.5" orient="auto">'
            f'<path class="arrmarker" d="M0,0 L8,4.5 L0,9 Z"/></marker></defs>{body}</svg></figure>')

N = lambda x, y, w, h, c='node': f'<rect class="{c}" x="{x}" y="{y}" width="{w}" height="{h}" rx="8"/>'
B = lambda x, y, w, h, c='bar': f'<rect class="{c}" x="{x}" y="{y}" width="{w}" height="{h}" rx="4"/>'
T = lambda x, y, s, c='txt': f'<text class="{c}" x="{x}" y="{y}" text-anchor="middle">{s}</text>'
LINE = lambda id_, x1, y1, x2, y2: f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" marker-end="url(#arr{id_})"/>'
PLAIN = lambda x1, y1, x2, y2: f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>'

