# ---- 插入 ----
hit = 0
for ch in notes['chapters']:
    for s in ch['sections']:
        for ss in s.get('subsections', []):
            if ss['section'] in FIGS:
                h = ss['html']
                h = re.sub(r'<p class="paragraph"><b>示意图：?</b></p><figure class="struct-fig">.*?</figure>\n?', '', h, flags=re.S)
                h = re.sub(r'<figure class="struct-fig">.*?</figure>\n?', '', h, flags=re.S)
                ss['html'] = h + '<p class="paragraph"><b>示意图：</b></p>' + FIGS[ss['section']]
                hit += 1
print(f'计网已插入 {hit} 张 SVG 图')

