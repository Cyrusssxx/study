def main():
    subjects = {'os': [], 'ds': [], 'co': [], 'cn': []}
    for qid in ANSWERS:
        subjects[qid.split('_')[0]].append(qid)

    total_filled = 0
    for s, ids in subjects.items():
        path = f'data/questions/{s}.json'
        with open(path, encoding='utf-8') as f:
            data = json.load(f)

        filled = 0
        for q in data['questions']:
            if q['id'] in ANSWERS:
                if q.get('answer'):
                    print(f"  [跳过] {q['id']} 已有答案 {q['answer']}")
                    continue
                ans, expl = ANSWERS[q['id']]
                q['answer'] = ans
                if not q.get('explanation'):
                    q['explanation'] = expl
                filled += 1

        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        remain = sum(1 for q in data['questions'] if not q.get('answer'))
        total_filled += filled
        print(f"{s}: 补全 {filled} 题, 剩余无答案 {remain} 题")

    print(f"\n共补全 {total_filled} 题")


if __name__ == '__main__':
    main()
