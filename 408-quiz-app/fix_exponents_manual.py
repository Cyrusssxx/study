os.makedirs(BACKUP, exist_ok=True)
applied, missed = 0, []
for k in ['ds', 'co', 'os', 'cn']:
    src = os.path.join(BASE, f'{k}.json')
    shutil.copy2(src, os.path.join(BACKUP, f'{k}.json'))
    d = json.load(io.open(src, encoding='utf-8'))
    for q in d['questions']:
        pairs = FIXES.get(q['id'])
        if not pairs:
            continue
        for old, new in pairs:
            hit = False
            for key in ['content', 'explanation']:
                if q.get(key) and old in q[key]:
                    q[key] = q[key].replace(old, new)
                    hit = True
            for ok_ in list((q.get('options') or {}).keys()):
                if old in q['options'][ok_]:
                    q['options'][ok_] = q['options'][ok_].replace(old, new)
                    hit = True
            if hit:
                applied += 1
            else:
                missed.append(f"{q['id']}: {old[:60]}")
    with io.open(src, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=2)

print('applied:', applied)
if missed:
    print('MISSED:')
    for m in missed:
        print(' ', m)
