for name, path in (('cn', 'pwa/data/cn.json'), ('co', 'pwa/data/co.json')):
    data = json.load(io.open(path, encoding='utf-8'))
    n = 0
    for qid, html in A.items():
        if not qid.startswith(name):
            continue
        hit = [q for q in data['questions'] if q['id'] == qid]
        assert hit, qid
        if 'kp_analysis' in hit[0]:
            continue
        hit[0]['kp_analysis'] = html
        n += 1
    json.dump(data, io.open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print(name, '注入', n, '题')
